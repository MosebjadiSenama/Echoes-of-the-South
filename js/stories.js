/* page elements */

const extraGrid = document.getElementById("extraGrid");
const extraSearch = document.getElementById("extraSearch");
const storyCount = document.getElementById("storyCount");

const loadingMessage = document.getElementById("extraLoading");
const errorMessage = document.getElementById("extraError");
const emptyMessage = document.getElementById("extraEmpty");

const filterButtons = document.querySelectorAll(".extra-filter");
const retryButton = document.getElementById("retryExtra");

let activeCategory = "all";
let imageCollection = {};



/* Automatically retrieve featured images from SAHO */

async function loadStoryImages() {

    const CACHE_KEY = "echoesSAHOImages";

    // Load previously retrieved images
    try {
        const cachedImages = sessionStorage.getItem(CACHE_KEY);

        if (cachedImages) {
            imageCollection = JSON.parse(cachedImages);
        }
    } catch (error) {
        console.warn("Image cache unavailable:", error);
    }

    // Only fetch stories without cached images
    const storiesWithoutImages = stories.filter(
        story => !imageCollection[story.id]
    );

    // Fetch SAHO articles in batches
    const batchSize = 8;

    for (let i = 0; i < storiesWithoutImages.length; i += batchSize) {

        const batch = storiesWithoutImages.slice(i, i + batchSize);

        await Promise.all(batch.map(async story => {

            try {

                const articleURL =
                    "https://proxy.cors.dev/" + story.source;

                const response = await fetch(articleURL, {
                    credentials: "omit"
                });

                if (!response.ok) {
                    throw new Error(`HTTP ${response.status}`);
                }

                const html = await response.text();

                const parser = new DOMParser();
                const page = parser.parseFromString(html, "text/html");

                const imageMeta =
                    page.querySelector('meta[property="og:image"]') ||
                    page.querySelector('meta[name="twitter:image"]');

                if (imageMeta && imageMeta.content) {

                    imageCollection[story.id] = new URL(
                        imageMeta.content,
                        story.source
                    ).href;

                }

            } catch (error) {

                console.warn(
                    "SAHO image unavailable:",
                    story.title,
                    error
                );

            }

        }));

        // Remember successfully retrieved images
        try {
            sessionStorage.setItem(
                CACHE_KEY,
                JSON.stringify(imageCollection)
            );
        } catch (error) {
            console.warn("Could not cache images:", error);
        }
    }
}




/* create story cards */

function createStoryCard(story) {
    const imageURL = imageCollection[story.id] || "";
    const card = document.createElement("a");

    card.className = "extra-card";
    card.href = story.source;
    card.target = "_blank";
    card.rel = "noopener noreferrer";

    const imageContainer = document.createElement("div");
    imageContainer.className = "extra-card-image";

    if (imageURL) {
        const image = document.createElement("img");

        image.src = imageURL;
        image.alt = story.title;
        image.loading = "lazy";

        image.onerror = () => {
            imageContainer.style.display = "none";
        };

        imageContainer.appendChild(image);
    } else {
        imageContainer.style.display = "none";
    }

    const content = document.createElement("div");
    content.className = "extra-card-content";

    const category = document.createElement("span");
    category.className = "extra-card-category";
    category.textContent = story.label;

    const title = document.createElement("h3");
    title.textContent = story.title;

    const description = document.createElement("p");
    description.textContent = story.description;

    const link = document.createElement("span");
    link.className = "extra-card-link";
    link.textContent = "READ THE STORY ↗";

    content.append(category, title, description, link);
    card.append(imageContainer, content);

    return card;
}


/* display stories */

function displayStories() {
    const searchTerm = extraSearch.value.toLowerCase().trim();

    const filteredStories = stories.filter(story => {
        const matchesCategory =
            activeCategory === "all" ||
            story.category === activeCategory;

        const matchesSearch =
            story.title.toLowerCase().includes(searchTerm) ||
            story.description.toLowerCase().includes(searchTerm) ||
            story.label.toLowerCase().includes(searchTerm);

        return matchesCategory && matchesSearch;
    });

    extraGrid.innerHTML = "";

    storyCount.textContent =
        `${filteredStories.length} ${filteredStories.length === 1 ? "story" : "stories"}`;

    emptyMessage.hidden = filteredStories.length !== 0;

    filteredStories.forEach(story => {
        extraGrid.appendChild(createStoryCard(story));
    });
}


/* category filters */

filterButtons.forEach(button => {
    button.addEventListener("click", () => {
        filterButtons.forEach(filter => {
            filter.classList.remove("active");
            filter.setAttribute("aria-pressed", "false");
        });

        button.classList.add("active");
        button.setAttribute("aria-pressed", "true");

        activeCategory = button.dataset.category;

        displayStories();
    });
});


/* search stories */

let searchScrollTimeout;

extraSearch.addEventListener("input", () => {

    displayStories();

    clearTimeout(searchScrollTimeout);

    if (extraSearch.value.trim().length > 0) {
        searchScrollTimeout = setTimeout(() => {
            extraGrid.scrollIntoView({
                behavior: "smooth",
                block: "start"
            });
        }, 500);
    }

});


/* initialise stories */

async function initialiseStories() {
    loadingMessage.hidden = false;
    errorMessage.hidden = true;
    emptyMessage.hidden = true;
    extraGrid.innerHTML = "";

    try {
        await loadStoryImages();

        displayStories();

        loadingMessage.hidden = true;

    } catch (error) {
        console.error("Could not initialise stories:", error);

        loadingMessage.hidden = true;
        errorMessage.hidden = false;
    }
}


/* retry */

retryButton.addEventListener("click", initialiseStories);


/* start page */

initialiseStories();
